"""
Musik oder nicht (Wunsch 15.10.2026): automatisch nur Eindeutiges, sonst
von Hand; die Wahl des Nutzers überschreibt keine Automatik. Der Bestand
geht einmal zurück auf "keine Musik" außer Eindeutigem.
"""
from app.services import lyrics_service, music_flag


def test_nur_eindeutiges_ist_automatisch_musik():
    assert music_flag.is_certainly_music("Adele - Topic", None)
    assert music_flag.is_certainly_music("Irgendwer", "Provided to YouTube by Sony Music\n\nHello")
    assert music_flag.is_certainly_music("Irgendwer", "Auto-generated by YouTube.")
    assert not music_flag.is_certainly_music("ARTEde", "Die Zukunft der Wirtschaft - Doku")
    assert not music_flag.is_certainly_music("Topic Talk", "Wie oft - Tipps (Live)")


def test_titel_vorschlag_entscheidet_nicht_ueber_musik():
    assert lyrics_service.suggest_artist_title("Adele - Hello (Official Music Video)") == \
        {"artist": "Adele", "song_title": "Hello"}
    assert lyrics_service.suggest_artist_title("E-Auto Test: Videoanleitung") == \
        {"artist": None, "song_title": None}


async def _video(db, vid, is_music=None, source=None, channel="Kanal", description=None):
    await db.execute(
        """INSERT INTO videos (id, title, status, channel_name, description, is_music, music_source)
           VALUES (?, 'T', 'ready', ?, ?, ?, ?)""", (vid, channel, description, is_music, source))


async def _flag(db, vid):
    row = await db.fetch_one("SELECT is_music, music_source FROM videos WHERE id = ?", (vid,))
    return row["is_music"], row["music_source"]


async def test_automatik_ueberschreibt_den_nutzer_nie(test_db):
    await _video(test_db, "vonhand0001", is_music=0, source="user")
    await _video(test_db, "offen000001")
    assert not await music_flag.apply_auto("vonhand0001", None, "Adele - Topic", None)
    assert await music_flag.apply_auto("offen000001", None, "Adele - Topic", None)
    assert await _flag(test_db, "vonhand0001") == (0, "user")
    assert await _flag(test_db, "offen000001") == (1, "auto")


async def test_von_hand_festlegen(test_db):
    await _video(test_db, "aaaaaaaaaaa")
    await _video(test_db, "bbbbbbbbbbb", is_music=1, source="auto")
    assert await music_flag.set_by_user(["aaaaaaaaaaa", "bbbbbbbbbbb"], False) == 2
    assert await _flag(test_db, "bbbbbbbbbbb") == (0, "user")


async def test_bestand_zuruecksetzen(test_db):
    await _video(test_db, "geraten0001", is_music=1)                       # alte Vermutung, ohne Beschreibung
    await _video(test_db, "geraten0002", is_music=1, channel=None, description="Ein Vlog")
    await _video(test_db, "vonhand0001", is_music=1, source="user")       # bleibt
    await _video(test_db, "topic000001", is_music=0, channel="Adele - Topic")
    await _video(test_db, "offen000001")
    assert await music_flag.reset_to_certain(test_db.conn) == 2
    assert await _flag(test_db, "geraten0001") == (0, None)
    assert await _flag(test_db, "geraten0002") == (0, None)
    assert await _flag(test_db, "vonhand0001") == (1, "user")
    assert await _flag(test_db, "topic000001") == (1, "auto")
    assert await _flag(test_db, "offen000001") == (None, None)
    stale = {r["video_id"] for r in await test_db.fetch_all("SELECT video_id FROM sidecar_stale")}
    assert stale == {"geraten0001", "geraten0002", "topic000001"}


async def _channel_video(db, vid, is_music=None, source=None):
    await db.execute(
        """INSERT INTO videos (id, title, status, channel_id, channel_name, is_music, music_source)
           VALUES (?, 'T', 'ready', 'UCmusik', 'Band', ?, ?)""", (vid, is_music, source))


async def test_musikkanal_mit_ausnahmen(test_db, monkeypatch):
    """Wunsch 15.10.2026: ganzen Kanal als Musikkanal markieren, Ausreißer
    einzeln abwählen; die Ausnahme bleibt, auch für künftige Videos gilt der Kanal."""
    async def no_refresh():
        return 0
    from app.services import meta_sidecar
    monkeypatch.setattr(meta_sidecar, "refresh_stale", no_refresh)
    await _channel_video(test_db, "song0000001")
    await _channel_video(test_db, "interview01", is_music=0, source="user")   # Ausnahme
    assert await music_flag.mark_channel("UCmusik", True) == 1
    assert await _flag(test_db, "song0000001") == (1, "channel")
    assert await _flag(test_db, "interview01") == (0, "user")

    await _channel_video(test_db, "neuersong01")                              # später geladen
    assert await music_flag.apply_auto("neuersong01", "UCmusik", "Band", None)
    assert await _flag(test_db, "neuersong01") == (1, "channel")

    await music_flag.mark_channel("UCmusik", False)
    assert await _flag(test_db, "song0000001") == (0, None)
    assert await _flag(test_db, "interview01") == (0, "user")

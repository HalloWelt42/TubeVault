"""
TubeVault – Musik oder nicht

Die eine Stelle für die Kennzeichnung videos.is_music und ihre Herkunft
(videos.music_source). Rangfolge, das Höhere gewinnt immer:
  'user'     vom Nutzer für dieses Video festgelegt (auch Ausnahmen)
  'channel'  der Kanal ist als Musikkanal markiert (music_channels)
  'auto'     eindeutig erkannt

Automatisch gilt nur als Musik, was eindeutig ist: Kanäle, die der Dienst
für Musik selbst erzeugt ("Interpret - Topic"), und deren Beschreibungen
("Provided to YouTube by ...", "Auto-generated by YouTube."). Alles andere
ordnet der Nutzer von Hand ein, und seine Wahl überschreibt die Automatik
nie.

Früher entschieden die Kategorie der Quelle, ein Bindestrich im Titel und
Schlagwörter ("ft" traf "oft", "Video" fast alles): 856 Videos galten als
Musik, großteils zu Unrecht (Messung 15.10.2026). Nutzerentscheidung
15.10.2026: alles zurück auf "keine Musik" außer Eindeutigem, ohne
Prüfliste - der Nutzer ordnet selbst ein.
"""
import asyncio
from typing import Iterable, Optional

from app.database import db

USER = "user"
CHANNEL = "channel"
AUTO = "auto"

SCHEMA_SQL = """
CREATE TABLE IF NOT EXISTS music_channels (
    channel_id TEXT PRIMARY KEY,
    marked_at TEXT DEFAULT (datetime('now'))
);
"""

TOPIC_SUFFIX = " - Topic"
CERTAIN_MARKERS = ("Provided to YouTube by", "Auto-generated by YouTube")

# Dieselbe Regel als SQL-Bedingung (für das Zurücksetzen des Bestands).
# COALESCE ist Pflicht: ohne Beschreibung wäre die Bedingung sonst NULL, und
# NOT NULL bleibt NULL - so blieben in v47 742 Videos ohne Beschreibung stehen.
CERTAIN_SQL = ("(COALESCE(channel_name, '') LIKE '%" + TOPIC_SUFFIX + "' OR "
               + " OR ".join(f"COALESCE(description, '') LIKE '%{m}%'" for m in CERTAIN_MARKERS) + ")")


def is_certainly_music(channel_name: Optional[str], description: Optional[str]) -> bool:
    """Eindeutig Musik - nur dann setzt die Automatik etwas."""
    if (channel_name or "").endswith(TOPIC_SUFFIX):
        return True
    return any(marker in (description or "") for marker in CERTAIN_MARKERS)


async def install_schema(connection) -> None:
    await connection.executescript(SCHEMA_SQL)
    await connection.commit()


async def is_music_channel(channel_id: Optional[str]) -> bool:
    return bool(channel_id) and bool(
        await db.fetch_val("SELECT 1 FROM music_channels WHERE channel_id = ?", (channel_id,)))


async def music_channel_ids() -> set[str]:
    return {r["channel_id"] for r in await db.fetch_all("SELECT channel_id FROM music_channels")}


async def apply_auto(video_id: str, channel_id: Optional[str], channel_name: Optional[str],
                     description: Optional[str]) -> bool:
    """Nach dem Laden: Video eines Musikkanals oder eindeutige Musik
    kennzeichnen; eine Wahl des Nutzers bleibt."""
    if await is_music_channel(channel_id):
        source = CHANNEL
    elif is_certainly_music(channel_name, description):
        source = AUTO
    else:
        return False
    cursor = await db.execute(
        """UPDATE videos SET is_music = 1, music_source = ?
           WHERE id = ? AND COALESCE(music_source, '') <> ?""", (source, video_id, USER))
    return cursor.rowcount == 1


async def mark_channel(channel_id: str, music: bool) -> int:
    """Kanal als Musikkanal markieren oder die Markierung aufheben. Alle
    Videos des Kanals folgen sofort - außer denen, die der Nutzer selbst
    festgelegt hat (Ausnahmen). Liefert die Zahl geänderter Videos."""
    if music:
        await db.execute("INSERT OR IGNORE INTO music_channels (channel_id) VALUES (?)", (channel_id,))
        # COALESCE überall: NOT mit NULL bliebe NULL und träfe kein Video
        changed = (f"channel_id = ? AND COALESCE(music_source, '') <> '{USER}' "
                   f"AND NOT (COALESCE(is_music, 0) = 1 AND COALESCE(music_source, '') = '{CHANNEL}')")
        await db.execute(f"INSERT OR IGNORE INTO sidecar_stale (video_id) SELECT id FROM videos WHERE {changed}", (channel_id,))
        cursor = await db.execute(
            f"UPDATE videos SET is_music = 1, music_source = '{CHANNEL}' WHERE {changed}", (channel_id,))
    else:
        await db.execute("DELETE FROM music_channels WHERE channel_id = ?", (channel_id,))
        await db.execute(
            f"INSERT OR IGNORE INTO sidecar_stale (video_id) SELECT id FROM videos WHERE channel_id = ? AND music_source = '{CHANNEL}'",
            (channel_id,))
        cursor = await db.execute(
            f"UPDATE videos SET is_music = 0, music_source = NULL WHERE channel_id = ? AND music_source = '{CHANNEL}'",
            (channel_id,))
        # was davon eindeutig Musik ist, bleibt es
        await db.execute(
            f"UPDATE videos SET is_music = 1, music_source = '{AUTO}' WHERE channel_id = ? AND music_source IS NULL AND {CERTAIN_SQL}",
            (channel_id,))
    from app.services import meta_sidecar
    asyncio.create_task(meta_sidecar.refresh_stale())
    return cursor.rowcount


async def set_by_user(video_ids: Iterable[str], is_music: bool) -> int:
    """Wahl des Nutzers für ein oder mehrere Videos; Begleitdateien folgen."""
    from app.services import meta_sidecar
    ids = list(dict.fromkeys(video_ids))
    if not ids:
        return 0
    marks = ",".join("?" * len(ids))
    cursor = await db.execute(
        f"""UPDATE videos SET is_music = ?, music_source = ?, updated_at = datetime('now')
            WHERE id IN ({marks})""", (int(is_music), USER, *ids))
    for video_id in ids:
        await meta_sidecar.write_sidecar(video_id)
    return cursor.rowcount


async def reset_to_certain(connection) -> int:
    """Bestand zurücksetzen: alles "keine Musik", außer Eindeutigem und außer
    dem, was der Nutzer schon selbst festgelegt hat. Begleitdateien der
    geänderten Videos werden zum Nachschreiben vorgemerkt. Liefert die Zahl
    der zurückgesetzten Videos."""
    # Gilt nur für vermutete Werte: Nutzerwahl und Musikkanäle bleiben
    changed = f"""(is_music = 1 AND COALESCE(music_source, '') NOT IN ('{USER}', '{CHANNEL}') AND NOT {CERTAIN_SQL})
                  OR (COALESCE(is_music, 0) = 0 AND COALESCE(music_source, '') NOT IN ('{USER}', '{CHANNEL}') AND {CERTAIN_SQL})"""
    await connection.execute(f"INSERT OR IGNORE INTO sidecar_stale (video_id) SELECT id FROM videos WHERE {changed}")
    cursor = await connection.execute(
        f"""UPDATE videos SET is_music = 0, music_source = NULL
            WHERE is_music = 1 AND COALESCE(music_source, '') NOT IN ('{USER}', '{CHANNEL}') AND NOT {CERTAIN_SQL}""")
    reset = cursor.rowcount
    await connection.execute(
        f"""UPDATE videos SET is_music = 1, music_source = '{AUTO}'
            WHERE COALESCE(music_source, '') NOT IN ('{USER}', '{CHANNEL}') AND {CERTAIN_SQL}""")
    await connection.commit()
    return reset
